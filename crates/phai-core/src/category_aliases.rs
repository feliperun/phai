/// Portuguese category for a slugified Pluggy category, if one is known.
pub fn pluggy_category_alias(slug: &str) -> Option<&'static str> {
    PLUGGY_CATEGORY_ALIASES
        .iter()
        .find_map(|(alias, canonical)| (*alias == slug).then_some(*canonical))
}
